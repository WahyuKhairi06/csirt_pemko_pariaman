<?php

namespace App\Enums;

// Tingkat keparahan advisori; tampilan badge: DESIGN.md bagian 7.3 (ikon + teks + warna, jangan warna saja).
enum Severity: string
{
    case Low = 'low';
    case Medium = 'medium';
    case High = 'high';
    case Critical = 'critical';

    public function label(): string
    {
        return match ($this) {
            self::Low => 'Rendah',
            self::Medium => 'Sedang',
            self::High => 'Tinggi',
            self::Critical => 'Kritis',
        };
    }

    /** Urutan untuk pengurutan "paling parah dulu". */
    public function rank(): int
    {
        return match ($this) {
            self::Low => 1,
            self::Medium => 2,
            self::High => 3,
            self::Critical => 4,
        };
    }
}
